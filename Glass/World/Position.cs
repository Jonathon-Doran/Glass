namespace Glass.World;

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Position
//
// A location in a zone's coordinate space, as decoded from a position update.  The values are fixed when
// the record is created; a new location is a new Position.
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
public class Position
{
    public readonly float X;
    public readonly float Y;
    public readonly float Z;

    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    // Position (constructor)
    //
    // Records the three coordinates of the location.
    //
    // x:  The x coordinate
    // y:  The y coordinate
    // z:  The z coordinate
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    public Position(float x, float y, float z)
    {
        X = x;
        Y = y;
        Z = z;
    }
}
