using Glass.Data.Models;

namespace Glass.Input;

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// IBuildLedReport
//
// Builds raw HID OUT reports for painting LEDs on a specific device type.
// One implementation exists per device type that supports LED output.
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
public interface IBuildLedReport
{
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    // Device
    //
    // The device type this builder handles.
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    KeyboardType Device { get; }

    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    // SetColors
    //
    // Updates the given keys' colors and returns the raw OUT report(s) needed
    // to make the device reflect just this change.
    //
    // changedColors:  One or more key names mapped to their new (R, G, B) color
    // Returns:         The raw report(s) to send, each including its report ID byte
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    IReadOnlyList<byte[]> SetColors(IReadOnlyDictionary<string, (byte R, byte G, byte B)> changedColors);
}